import assert from 'node:assert/strict';
import puppeteer from 'puppeteer-core';
const base = process.env.BOARD_TEST_URL ?? 'http://localhost:3095';
const browser = await puppeteer.launch({ executablePath: process.env.BOARD_TEST_BROWSER ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const button = name => page.locator(`::-p-aria([name="${name}"][role="button"])`);
try {
  await page.setViewport({ width: 1440, height: 1000 });
  await page.goto(`${base}/app/boards/new`, { waitUntil: 'networkidle0' });
  await page.locator('#title').fill('Zulu board');
  await page.waitForFunction(() => !document.querySelector('[aria-label="Board folder"]').disabled);
  await page.select('[aria-label="Board folder"]', '$new');
  await page.locator('[role="dialog"] input').fill('Studies');
  await button('Create and use folder').click();
  await page.waitForFunction(() => !document.querySelector('[role="dialog"]'));
  const studies = await page.$eval('[aria-label="Board folder"]', el => el.value);
  assert.ok(studies);
  await button('Create board').click();
  await page.waitForSelector('.react-flow');
  await page.goto(`${base}/app/boards`, { waitUntil: 'networkidle0' });
  assert.equal(await page.$eval('[aria-label="Folder for Zulu board"]', el => el.value), studies);
  await button('Studies').click();
  await page.locator('a[href*="/app/boards/new?folder="]').click();
  await page.waitForFunction(id => document.querySelector('[aria-label="Board folder"]')?.value === id, {}, studies);
  await page.locator('#title').fill('Alpha board');
  await page.select('[aria-label="Board folder"]', '$new');
  await page.locator('[role="dialog"] input').fill('Grammar');
  assert.equal(await page.$eval('[role="dialog"] select', el => el.value), studies);
  await button('Create and use folder').click();
  await page.waitForFunction(() => !document.querySelector('[role="dialog"]'));
  const grammar = await page.$eval('[aria-label="Board folder"]', el => el.value);
  await button('Create board').click();
  await page.waitForSelector('.react-flow');
  await page.goto(`${base}/app/boards`, { waitUntil: 'networkidle0' });
  assert.equal(await page.$eval('[aria-label="Folder for Alpha board"]', el => el.value), grammar);
  await page.select('[aria-label="Folder for Zulu board"]', '$new');
  await page.locator('[role="dialog"] input').fill('New destination');
  await page.select('[role="dialog"] select', '');
  await button('Create and use folder').click();
  await page.waitForFunction(() => !document.querySelector('[role="dialog"]'));
  const destination = await page.$eval('[aria-label="Folder for Zulu board"]', el => el.value);
  assert.notEqual(destination, studies);
  await page.select('[aria-label="Folder for Alpha board"]', '$new');
  await page.keyboard.press('Escape');
  assert.equal(await page.$eval('[aria-label="Folder for Alpha board"]', el => el.value), grammar);
  await page.select('[aria-label="Sort boards"]', 'title-asc');
  await page.waitForFunction(() => document.querySelector('h3 a')?.textContent === 'Alpha board');
  await page.reload({ waitUntil: 'networkidle0' });
  assert.equal(await page.$eval('[aria-label="Sort boards"]', el => el.value), 'title-asc');
  assert.equal(await page.$eval('[aria-label="Folder for Zulu board"]', el => el.value), destination);
  await page.select('[aria-label="Sort boards"]', 'title-desc');
  await page.waitForFunction(() => document.querySelector('h3 a')?.textContent === 'Zulu board');
  await page.screenshot({ path: '.tmp/board-folders-sort.png' });
  assert.deepEqual(errors, []);
  console.log('PASS: Create in new folder, inherited folder, nested destination, create during move, cancel, persisted sorting and assignments');
} catch (error) {
  console.log(await page.evaluate(() => document.body.innerText));
  await page.screenshot({ path: '.tmp/board-folders-failure.png' });
  throw error;
} finally { await browser.close(); }
